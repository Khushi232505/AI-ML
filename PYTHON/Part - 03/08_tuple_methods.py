tup = (1, 2, 3, 4, 3, 9)

print(tup.count(3)) #  counts total occurences

print(tup.index(4)) # returns first occurence index

print(len(tup)) # tells us the lenght of the tuple

# Concatination
a = (1, 2, 4)
b = (4, 5, 7)
print(a+b)

# Membership(in)
print((3 in tup))
print(5 in tup)

# Repetition
t = (3,) * 5
print(t)
